use std::fs;

use super::terminal::{self, Colors};
use super::{config_home, hex, state_home, write};
use crate::theme::Theme;

const NAMES: [&str; 8] = ["black", "red", "green", "yellow", "blue", "magenta", "cyan", "white"];

/*
 * a colors file that alacritty.toml imports; alacritty watches its
 * imports, so open windows recolor on their own
 */
pub fn export(theme: &Theme) {
    let colors = terminal::colors(theme);

    let path = format!("{}/terminal-colors-alacritty.toml", state_home());

    write(&path, &config(theme, &colors));

    add_import(&path);
}

fn config(theme: &Theme, colors: &Colors) -> String {
    let mut text = String::from("# generated by amane, do not edit\n");

    let mut section = |name: &str, entries: &[(&str, String)]| {
        text.push_str(&format!("\n[colors.{name}]\n"));

        for (key, value) in entries {
            text.push_str(&format!("{key} = \"{value}\"\n"));
        }
    };

    section(
        "primary",
        &[("background", hex(colors.background)), ("foreground", hex(colors.foreground))],
    );

    section("cursor", &[("text", hex(theme.on_accent)), ("cursor", hex(colors.cursor))]);

    section(
        "selection",
        &[("text", hex(colors.foreground)), ("background", hex(colors.selection))],
    );

    let normal: Vec<(&str, String)> = NAMES.iter().zip(&colors.ansi[..8]).map(|(name, color)| (*name, hex(*color))).collect();
    let bright: Vec<(&str, String)> = NAMES.iter().zip(&colors.ansi[8..]).map(|(name, color)| (*name, hex(*color))).collect();

    section("normal", &normal);
    section("bright", &bright);

    text
}

/*
 * puts the colors file last in alacritty.toml's imports, so it wins over
 * the other imports; colors set in alacritty.toml itself still win over it
 */
fn add_import(path: &str) {
    let config = format!("{}/alacritty/alacritty.toml", config_home());

    let Ok(text) = fs::read_to_string(&config) else {
        return;
    };

    if text.contains(path) {
        return;
    }

    let entry = format!("\"{path}\"");

    let mut lines: Vec<String> = text.lines().map(String::from).collect();

    let existing = lines.iter().position(|line| {
        let line = line.trim_start();

        line.starts_with("import") && line.contains('[') && line.trim_end().ends_with(']')
    });

    if let Some(index) = existing {
        let line = lines[index].trim_end();

        let inside = line[line.find('[').unwrap_or(0) + 1..line.len() - 1].trim().trim_end_matches(',');

        lines[index] = if inside.is_empty() {
            format!("import = [{entry}]")
        } else {
            format!("import = [{inside}, {entry}]")
        };
    } else if let Some(index) = lines.iter().position(|line| line.trim() == "[general]") {
        lines.insert(index + 1, format!("import = [{entry}]"));
    } else {
        lines.insert(0, String::from("[general]"));
        lines.insert(1, format!("import = [{entry}]"));
        lines.insert(2, String::new());
    }

    let _ = fs::write(&config, lines.join("\n") + "\n");
}
