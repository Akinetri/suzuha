/*
 * a telegram desktop theme: a zip with the palette and the wallpaper as
 * the chat background; the palette is the default one recolored, grays
 * turned into the theme's surfaces and text, blues into the accent, reds
 * and greens into danger and success
 */
pub fn export(theme: &Theme) {
    let folder = format!("{}/telegram", state_home());

    let _ = fs::create_dir_all(&folder);

    let colors = format!("{folder}/colors.tdesktop-theme");

    write(&colors, &palette(theme));

    let mut files = vec![colors];

    let background = format!("{folder}/background.jpg");

    if chat_background(&background) {
        files.push(background);
    }

    let partial = format!("{folder}/theme.zip");

    let _ = fs::remove_file(&partial);

    let zipped = Command::new("zip").args(["-q", "-j", &partial]).args(&files).status();

    if !zipped.is_ok_and(|status| status.success()) {
        eprintln!("amane: failed to zip the telegram theme, is zip installed?");

        return;
    }

    /*
     * written over in place rather than renamed, so the file telegram
     * watches stays the same file and its watcher sees the change
     */
    let Ok(bytes) = fs::read(&partial) else {
        return;
    };

    let _ = fs::write(format!("{}/{THEME}", state_home()), bytes);
}

fn palette(theme: &Theme) -> String {
    let mut text = String::from("// generated by amane, do not edit\n");

    for line in PALETTE.lines() {
        let Some((key, value)) = line.split_once(':') else {
            continue;
        };

        // "#2dad2d | boxTextFgGood;" names a fallback for older apps, the value is enough here
        let value = value.trim().trim_end_matches(';');
        let value = value.split('|').next().unwrap_or_default().trim();

        let shown = match (overridden(key, theme), parse(value)) {
            (Some(color), _) => hex(color),
            (None, Some(color)) => hex(recolor(key, color, theme)),

            // a name of another key, which follows that key's new color
            (None, None) => String::from(value),
        };

        text.push_str(&format!("{key}: {shown};\n"));
    }

    text
}

// the keys that say most about how telegram looks, set straight from the theme
fn overridden(key: &str, theme: &Theme) -> Option<Color> {
    let accent_tint = |amount: f32| theme::mix(theme.surface, theme.accent, amount);

    let color = match key {
        "windowBg" => theme.background,
        "windowFg" | "windowBoldFg" | "windowBoldFgOver" | "msgServiceFg" => theme.text,
        "windowBgOver" => theme.hover_surface,
        "windowBgRipple" | "windowShadowFgFallback" => theme.selected_surface,
        "windowSubTextFg" | "windowSubTextFgOver" => theme.secondary_text,
        "windowBgActive" | "windowActiveTextFg" | "dialogsBgActive" => theme.accent,
        "windowFgActive" | "activeButtonFg" | "dialogsOnlineBadgeFgActive" => theme.on_accent,
        "activeButtonBgOver" => theme.accent_hover,
        "activeButtonBgRipple" => theme::mix(theme.accent, theme.on_accent, 0.15),
        "activeButtonSecondaryFg" | "dialogsDraftFgActive" => theme::mix(theme.on_accent, theme.accent, 0.3),
        "dialogsSendingIconFgActive" => theme::with_opacity(theme.on_accent, 0.6),
        "attentionButtonFg" | "attentionButtonFgOver" => theme.danger,
        "menuSeparatorFg" | "inputBorderFg" => theme.border,

        // incoming messages on the surface, the user's own tinted with the accent
        "msgInBg" => theme.surface,
        "msgInBgSelected" => accent_tint(0.25),
        "msgOutBg" => accent_tint(0.3),
        "msgOutBgSelected" => accent_tint(0.45),
        "msgInDateFg" => theme.muted_text,
        "msgOutDateFg" => theme::mix(theme.muted_text, theme.accent, 0.4),

        // the date and service bubbles float over the wallpaper
        "msgServiceBg" => theme::with_opacity(theme.background, 0.6),
        "msgServiceBgSelected" => theme::with_opacity(theme.selected_surface, 0.7),

        // the folder list down the left side, dark blue by default
        "sideBarBg" => theme.surface,
        "sideBarBgActive" => theme.selected_surface,
        "sideBarBgRipple" => theme.hover_surface,
        "sideBarTextFg" | "sideBarIconFg" => theme.secondary_text,
        "sideBarTextFgActive" | "sideBarIconFgActive" | "sideBarBadgeBg" => theme.accent,
        "sideBarBadgeBgMuted" => theme.muted_text,
        "sideBarBadgeFg" => theme.on_accent,

        _ => return None,
    };

    Some(color)
}

fn recolor(key: &str, color: Color, theme: &Theme) -> Color {
    if KEPT.iter().any(|prefix| key.starts_with(prefix)) || key.contains("Shadow") || key.contains("Inverted") {
        return color;
    }

    let alpha = f32::from(color.alpha()) / 255.0;

    let shade = hsl::from_color(color);

    let lightness = shade.lightness;

    // the scroll bars over the wallpaper keep their see-through look in the text's color
    if key.starts_with("historyScroll") {
        return theme::with_opacity(theme.text, alpha);
    }

    if shade.saturation < 0.12 {
        if alpha < 1.0 {
            // dark veils dim things in every theme, light ones turn into the theme's background
            return if key.to_ascii_lowercase().contains("scroll") {
                theme::with_opacity(theme.text, alpha)
            } else if lightness > 0.5 {
                theme::with_opacity(theme.background, alpha)
            } else {
                color
            };
        }

        // white is the background, black the text, every gray between them
        return theme::mix(theme.background, theme.text, 1.0 - lightness);
    }

    let hue = shade.hue;

    let outgoing = OUTGOING.iter().any(|prefix| key.starts_with(prefix));

    let base = if (170.0..=265.0).contains(&hue) || (outgoing && (75.0..170.0).contains(&hue)) {
        theme.accent
    } else if !(20.0..335.0).contains(&hue) {
        theme.danger
    } else if (75.0..170.0).contains(&hue) {
        theme.success
    } else {
        // yellows and purples have no place in the theme, they stay as they are
        return color;
    };

    // a pale tint is a little of the color over the background, a deep one leans toward the text
    let tinted = if lightness >= 0.5 {
        theme::mix(theme.background, base, ((1.0 - lightness) / 0.45).clamp(0.0, 1.0))
    } else {
        theme::mix(base, theme.text, ((0.5 - lightness) * 0.8).clamp(0.0, 0.4))
    };

    theme::with_opacity(tinted, alpha)
}

// the wallpaper as a jpeg telegram can read, none when there is no wallpaper or magick can't read it
fn chat_background(path: &str) -> bool {
    let wallpaper = Wallpaper::read().path.clone();

    if wallpaper.is_empty() {
        return false;
    }

    Command::new("magick")
        .args([&wallpaper, "-auto-orient", "-resize", "1920x1920>", "-quality", "88", path])
        .status()
        .is_ok_and(|status| status.success())
}

// "#rrggbb" or "#rrggbbaa"
fn parse(value: &str) -> Option<Color> {
    let digits = value.strip_prefix('#')?;

    let channel = |index: usize| u8::from_str_radix(digits.get(index..index + 2)?, 16).ok();

    match digits.len() {
        6 => Some(Color::rgb(channel(0)?, channel(2)?, channel(4)?)),
        8 => Some(Color::rgba(channel(0)?, channel(2)?, channel(4)?, channel(6)?)),
        _ => None,
    }
}

fn hex(color: Color) -> String {
    let rgb = super::hex(color);

    if color.alpha() == 255 {
        return rgb;
    }

    format!("{rgb}{:02x}", color.alpha())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_key_gets_a_valid_value() {
        let theme = theme::for_mode(Some(false));

        let text = palette(&theme);

        let lines: Vec<&str> = text.lines().skip(1).collect();

        assert_eq!(lines.len(), PALETTE.lines().count());

        for line in lines {
            let (_, value) = line.split_once(": ").expect("failed to split a palette line");

            let value = value.trim_end_matches(';');

            assert!(parse(value).is_some() || value.chars().all(|c| c.is_ascii_alphanumeric()), "{line}");
        }
    }
}
